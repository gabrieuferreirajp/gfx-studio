import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createDocument, createObject } from '../src/document/model.ts';
import { createHistory, historyReducer as reduce, isDirty } from '../src/state/history.ts';

test('desenhar e mover por centenas de eventos geram uma entrada por gesto', () => {
  let state = createHistory(createDocument());
  const object = createObject('rectangle', 0, 0, '#7774e7');
  state = reduce(state, { type: 'begin' });
  state = reduce(state, { type: 'edit', action: { type: 'add', object } });
  for (let width = 1; width <= 200; width++) state = reduce(state, { type: 'edit', action: { type: 'update', id: object.id, patch: { width } } });
  state = reduce(state, { type: 'commit' });
  assert.equal(state.past.length, 1);
  state = reduce(state, { type: 'begin' });
  for (let x = 0; x <= 200; x++) state = reduce(state, { type: 'edit', action: { type: 'update', id: object.id, patch: { x } } });
  state = reduce(state, { type: 'commit' });
  assert.equal(state.past.length, 2);
  state = reduce(state, { type: 'undo' });
  assert.equal(state.present.objects[0].x, 0);
  assert.equal(state.present.objects[0].width, 200);
  state = reduce(state, { type: 'undo' });
  assert.equal(state.present.objects.length, 0);
  state = reduce(reduce(state, { type: 'redo' }), { type: 'redo' });
  assert.equal(state.present.objects[0].x, 200);
  assert.equal(state.present.objects[0].id, object.id);
});
test('edição de texto é agrupada e desfazer funciona com transação em andamento', () => {
  const document = createDocument();
  const object = createObject('text', 10, 20, '#ffffff');
  document.objects.push(object);
  let state = reduce(createHistory(document), { type: 'begin' });
  for (const text of ['A', 'Ab', 'Abc']) state = reduce(state, { type: 'edit', action: { type: 'update', id: object.id, patch: { text } } });
  state = reduce(state, { type: 'undo' });
  assert.equal(state.present.objects[0].text, 'Seu texto');
  assert.equal(reduce(state, { type: 'redo' }).present.objects[0].text, 'Abc');
});
test('operações sem mudança não criam histórico nem invalidam refazer', () => {
  const document = createDocument();
  const object = createObject('ellipse', 1, 2, '#ffffff');
  document.objects.push(object);
  let state = createHistory(document);
  state = reduce(state, { type: 'edit', action: { type: 'delete', id: 'ausente' } });
  assert.equal(state.past.length, 0);
  state = reduce(state, { type: 'edit', action: { type: 'delete', id: object.id } });
  state = reduce(state, { type: 'undo' });
  state = reduce(state, { type: 'begin' });
  state = reduce(state, { type: 'edit', action: { type: 'update', id: object.id, patch: { x: 50 } } });
  state = reduce(state, { type: 'edit', action: { type: 'update', id: object.id, patch: { x: 1 } } });
  state = reduce(state, { type: 'commit' });
  assert.equal(state.past.length, 0);
  assert.equal(state.future.length, 1);
  assert.equal(isDirty(state), false);
});
test('nova edição após undo descarta refazer; salvo e carregado estabelecem o estado limpo', () => {
  let state = createHistory(createDocument());
  const object = createObject('rectangle', 0, 0, '#7774e7');
  state = reduce(state, { type: 'edit', action: { type: 'add', object } });
  assert.equal(isDirty(state), true);
  state = reduce(state, { type: 'saved', snapshot: JSON.stringify(state.present) });
  assert.equal(isDirty(state), false);
  state = reduce(state, { type: 'undo' });
  assert.equal(isDirty(state), true);
  state = reduce(state, { type: 'redo' });
  assert.equal(isDirty(state), false);
  state = reduce(state, { type: 'undo' });
  state = reduce(state, { type: 'edit', action: { type: 'add', object: createObject('ellipse', 5, 5, '#000000') } });
  assert.equal(state.future.length, 0);
  const loaded = createDocument();
  state = reduce(state, { type: 'load', document: loaded });
  assert.deepEqual(state.present, loaded);
  assert.equal(state.past.length, 0);
  assert.equal(state.future.length, 0);
  assert.equal(isDirty(state), false);
});
test('histórico é limitado a cem operações', () => {
  let state = createHistory(createDocument());
  for (let i = 0; i < 110; i++) state = reduce(state, { type: 'edit', action: { type: 'add', object: createObject('rectangle', i, 0, '#000000') } });
  assert.equal(state.past.length, 100);
});
